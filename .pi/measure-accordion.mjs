import { chromium } from 'playwright-core';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const page=await browser.newPage({viewport:{width:1800,height:1200}});
page.on('console',m=>console.log('console',m.type(),m.text()));
page.on('pageerror',e=>console.error('pageerror',e));
await page.goto('http://127.0.0.1:5199/.pi/accordion-test.html');
await page.waitForSelector('[data-cell]');
const result=await page.$$eval('[data-cell]', els=>els.map(el=>({cell:el.getAttribute('data-cell'),rect:{w:el.getBoundingClientRect().width,h:el.getBoundingClientRect().height},border:getComputedStyle(el).borderBottomWidth,trigger:el.querySelector('button')?.getBoundingClientRect().height,content:el.querySelector('[id]')?.getBoundingClientRect().height})));
console.log(JSON.stringify(result,null,2));
const faq=page.locator('#independent .AccordionRow, #independent [class*="root"]').filter({has:page.locator('button')});
const buttons=page.locator('#independent button[aria-expanded]');
console.log('faq buttons',await buttons.count());
for(let i=0;i<await buttons.count();i++)console.log(i,await buttons.nth(i).getAttribute('aria-expanded'));
await buttons.nth(0).click();
console.log('after click',await buttons.nth(0).getAttribute('aria-expanded'),await buttons.nth(1).getAttribute('aria-expanded'));
await buttons.nth(1).press('Enter');
console.log('after enter',await buttons.nth(0).getAttribute('aria-expanded'),await buttons.nth(1).getAttribute('aria-expanded'));
await buttons.nth(2).press(' ');
console.log('after space',await buttons.nth(2).getAttribute('aria-expanded'));
console.log('associations',await buttons.evaluateAll(bs=>bs.map(b=>({controls:b.getAttribute('aria-controls'),exists:!!document.getElementById(b.getAttribute('aria-controls')||'')}))));
await browser.close();
